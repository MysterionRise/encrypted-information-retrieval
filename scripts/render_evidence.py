"""Render the generated sections of docs/PORTFOLIO_EVIDENCE.md from JSON results.

    python scripts/render_evidence.py          # rewrite the generated sections in place
    python scripts/render_evidence.py --check  # exit 1 if they are out of date

A generated section sits between ``<!-- generated:NAME:begin -->`` and
``<!-- generated:NAME:end -->``; everything outside the markers is written by hand.

Sections:
- ``benchmarks``: the retrieval benchmark summary, from
  ``benchmarks/reports/<engine>/retrieval_<N>.json`` (encrypted_ir.tools.benchmark_retrieval).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "docs" / "PORTFOLIO_EVIDENCE.md"
REPORTS = ROOT / "benchmarks" / "reports"


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def _pair(op: dict[str, Any]) -> str:
    return f"{_ms(op['p50_ms'])} / {_ms(op['p95_ms'])}"


def _engine(result: dict[str, Any]) -> str:
    db = result["provenance"]["database"]
    if db["dialect"] == "sqlite":
        where = "in memory" if ":memory:" in db["url"] or "%3Amemory%3A" in db["url"] else "file"
        return f"SQLite {db['server_version']} ({where})"
    return f"PostgreSQL {db['server_version']}"


def load_benchmarks(reports: Path = REPORTS) -> list[tuple[Path, dict[str, Any]]]:
    """Every retrieval result, ordered by engine directory and corpus size."""
    found = []
    for path in reports.glob("*/retrieval_*.json"):
        result = json.loads(path.read_text())
        found.append((path, result))
    return sorted(found, key=lambda item: (item[0].parent.name, item[1]["parameters"]["documents"]))


def render_benchmarks(results: list[tuple[Path, dict[str, Any]]], root: Path = ROOT) -> str:
    """The benchmark section: one row per engine and corpus size, with its provenance."""
    if not results:
        return "No retrieval benchmark results are committed.\n"
    lines = [
        "Generated by `scripts/render_evidence.py` from the JSON reports. Times are milliseconds,",
        "p50 / p95, measured in one process with the database on the same machine; see",
        "[benchmarks/README.md](../benchmarks/README.md) for what they do not show.",
        "",
        "| Engine | Documents | Ingest docs/s | Ingest one | Search AND (limit 100) | Get one | "
        "RAG top 10 with plaintext | Report |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    machines = {}
    for path, result in results:
        ops = result["operations"]
        prov = result["provenance"]
        report = path.with_suffix(".md").relative_to(root).as_posix()
        lines.append(
            f"| {_engine(result)} | {result['parameters']['documents']} | "
            f"{result['ingest']['documents_per_second']:.0f} | {_pair(ops['ingest'])} | "
            f"{_pair(ops['search_and'])} | {_pair(ops['get_document'])} | "
            f"{_pair(ops['rag_retrieve'])} | [{path.stem}](../{report}) |"
        )
        dirty = " (uncommitted changes)" if prov["dirty_tree"] else ""
        machine = (
            f"commit `{prov['commit'][:12]}`{dirty}; {prov['cpu_model']}, {prov['cpu_count']} "
            f"logical cores; {prov['os']}; {prov['python']}"
        )
        machines.setdefault((_engine(result), machine), []).append(prov["generated_at"])
    lines.append("")
    for (engine, machine), dates in machines.items():
        lines.append(f"- {engine}: runs started {min(dates)} to {max(dates)} (UTC) on {machine}.")
    return "\n".join(lines) + "\n"


SECTIONS = {"benchmarks": lambda: render_benchmarks(load_benchmarks())}


def apply(text: str, sections: dict[str, str]) -> str:
    """Replace the body of every generated section named in ``sections``."""
    for name, body in sections.items():
        pattern = re.compile(
            rf"(<!-- generated:{name}:begin -->\n).*?(<!-- generated:{name}:end -->)", re.DOTALL
        )
        if not pattern.search(text):
            raise SystemExit(f"{EVIDENCE.name} has no generated:{name} markers")
        text = pattern.sub(lambda m, body=body: m.group(1) + body + m.group(2), text)
    return text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="Exit 1 if out of date")
    args = parser.parse_args(argv)

    current = EVIDENCE.read_text()
    rendered = apply(current, {name: render() for name, render in SECTIONS.items()})
    if args.check:
        if rendered != current:
            print(f"{EVIDENCE} is out of date: run scripts/render_evidence.py", file=sys.stderr)
            return 1
        return 0
    EVIDENCE.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
